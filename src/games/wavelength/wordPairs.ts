/**
 * Get a random pair not in usedIndices and not from lastCategory.
 * Returns { pair, index } or null if pool is exhausted.
 */
export function getRandomPair(
  usedIndices: number[],
  lastCategory: string | null,
): { pair: WordPair; index: number } | null {
  const usedSet = new Set(usedIndices);

  // Build pool: exclude used pairs and pairs from the same category as last round
  const pool: number[] = [];
  for (let i = 0; i < ALL_PAIRS.length; i++) {
    if (usedSet.has(i)) continue;
    if (lastCategory && ALL_PAIRS[i].category === lastCategory) continue;
    pool.push(i);
  }

  // If pool is empty because of category restriction, try without it
  if (pool.length === 0) {
    for (let i = 0; i < ALL_PAIRS.length; i++) {
      if (!usedSet.has(i)) pool.push(i);
    }
  }

  if (pool.length === 0) return null; // all pairs exhausted

  const idx = pool[Math.floor(Math.random() * pool.length)];
  return { pair: ALL_PAIRS[idx], index: idx };
}
